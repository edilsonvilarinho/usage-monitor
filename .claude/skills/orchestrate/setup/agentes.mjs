// Configuração dos agentes por projeto (primeira execução).
// Uso: node agentes.mjs verificar            -> bloco curto de status (injetado no SKILL.md)
//      node agentes.mjs detectar             -> JSON com stack e comandos detectados
//      node agentes.mjs instalar [--sobrescrever]  -> grava os agentes em <projeto>/.claude/agents/
//      node agentes.mjs dispensar            -> registra que o projeto usa os agentes genéricos
// Só lê arquivos de manifesto; não executa nada do projeto.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirEscritorio, parseArgs, raizRepo } from '../portal/collector.mjs';

const AQUI = path.dirname(fileURLToPath(import.meta.url));
export const DIR_MODELOS = path.join(AQUI, '..', 'agents');
export const AGENTES = ['explorer', 'test-runner', 'backend-dev', 'frontend-dev', 'prototype-dev'];

const lerTexto = (arq) => { try { return fs.readFileSync(arq, 'utf8'); } catch { return null; } };
const lerJson = (arq) => { try { return JSON.parse(lerTexto(arq)); } catch { return null; } };
const existe = (arq) => fs.existsSync(arq);

const FRAMEWORKS_FRONT = ['react', 'vue', 'svelte', '@angular/core', 'next', 'nuxt', 'solid-js', 'astro'];
const SCRIPTS_NODE = ['test', 'typecheck', 'lint', 'build'];

/** Lê só manifestos. `comandos` traz o que está declarado; `convencao` traz o padrão do ecossistema. */
export function detectar(raiz) {
  const stacks = [];
  const comandos = {};
  const convencao = {};
  const arq = (...p) => path.join(raiz, ...p);

  const pkg = lerJson(arq('package.json'));
  if (pkg) {
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    const front = FRAMEWORKS_FRONT.filter((f) => f in deps);
    const ts = existe(arq('tsconfig.json')) || 'typescript' in deps;
    stacks.push({ nome: ts ? 'Node.js + TypeScript' : 'Node.js', evidencia: 'package.json', frontend: front });
    const gerenciador = existe(arq('pnpm-lock.yaml')) ? 'pnpm' : existe(arq('yarn.lock')) ? 'yarn' : 'npm';
    for (const s of SCRIPTS_NODE) {
      if (pkg.scripts && s in pkg.scripts) comandos[s] = s === 'test' && gerenciador === 'npm' ? 'npm test' : `${gerenciador} run ${s}`;
    }
  }
  if (existe(arq('pom.xml'))) {
    stacks.push({ nome: 'Java (Maven)', evidencia: 'pom.xml', frontend: [] });
    convencao.test = existe(arq('mvnw')) ? './mvnw test' : 'mvn test';
  }
  const gradle = ['build.gradle', 'build.gradle.kts'].find((f) => existe(arq(f)));
  if (gradle) {
    stacks.push({ nome: 'Java/Kotlin (Gradle)', evidencia: gradle, frontend: [] });
    convencao.test = existe(arq('gradlew')) ? './gradlew test' : 'gradle test';
  }
  if (existe(arq('go.mod'))) {
    stacks.push({ nome: 'Go', evidencia: 'go.mod', frontend: [] });
    convencao.test = 'go test ./...';
  }
  if (existe(arq('Cargo.toml'))) {
    stacks.push({ nome: 'Rust', evidencia: 'Cargo.toml', frontend: [] });
    convencao.test = 'cargo test';
  }
  const py = ['pyproject.toml', 'requirements.txt', 'setup.py'].find((f) => existe(arq(f)));
  if (py) {
    stacks.push({ nome: 'Python', evidencia: py, frontend: [] });
    const txt = (lerTexto(arq(py)) ?? '').toLowerCase();
    if (txt.includes('pytest')) convencao.test = 'pytest';
  }
  const dotnet = fs.readdirSync(raiz).find((f) => /\.(sln|csproj)$/.test(f));
  if (dotnet) {
    stacks.push({ nome: '.NET', evidencia: dotnet, frontend: [] });
    convencao.test = 'dotnet test';
  }

  return {
    raiz,
    stacks,
    comandos,
    convencao,
    regrasProjeto: ['CLAUDE.md', 'AGENTS.md'].filter((f) => existe(arq(f))),
  };
}

/** Estado: `configurado` por agentes do projeto ou marcador; `faltam` lista os ausentes no projeto. */
export function estado(raiz) {
  const dirAgentes = path.join(raiz, '.claude', 'agents');
  const noProjeto = AGENTES.filter((a) => existe(path.join(dirAgentes, `${a}.md`)));
  const noUsuario = AGENTES.filter((a) => existe(path.join(os.homedir(), '.claude', 'agents', `${a}.md`)));
  const marcador = lerJson(path.join(dirEscritorio(raiz), 'agentes.json'));
  const configurado = noProjeto.length === AGENTES.length || Boolean(marcador?.configurado);
  return { configurado, noProjeto, noUsuario, faltam: AGENTES.filter((a) => !noProjeto.includes(a)), marcador };
}

function blocoProjeto(det) {
  const linhas = ['', '## Project context', '', 'Generated by `orchestrate` setup from the project manifests. Edit freely.', ''];
  if (!det.stacks.length) linhas.push('- Stack: not detected (no known manifest in the project root).');
  for (const s of det.stacks) {
    linhas.push(`- Stack: ${s.nome} (evidence: \`${s.evidencia}\`${s.frontend.length ? `; front end: ${s.frontend.join(', ')}` : ''})`);
  }
  for (const [k, v] of Object.entries(det.comandos)) linhas.push(`- \`${k}\` command (declared in package.json): \`${v}\``);
  for (const [k, v] of Object.entries(det.convencao)) linhas.push(`- \`${k}\` command (ecosystem convention, not verified in this project): \`${v}\``);
  if (det.regrasProjeto.length) linhas.push(`- Read first: ${det.regrasProjeto.map((f) => `\`${f}\``).join(', ')} (project rules).`);
  return linhas.join('\n') + '\n';
}

export function instalar(raiz, { sobrescrever = false } = {}) {
  const det = detectar(raiz);
  const destino = path.join(raiz, '.claude', 'agents');
  fs.mkdirSync(destino, { recursive: true });
  const criados = [];
  const mantidos = [];
  for (const nome of AGENTES) {
    const alvo = path.join(destino, `${nome}.md`);
    if (existe(alvo) && !sobrescrever) { mantidos.push(nome); continue; }
    const modelo = lerTexto(path.join(DIR_MODELOS, `${nome}.md`));
    if (modelo === null) throw new Error(`modelo ausente: ${path.join(DIR_MODELOS, `${nome}.md`)}`);
    fs.writeFileSync(alvo, modelo.replace(/\s*$/, '\n') + blocoProjeto(det));
    criados.push(nome);
  }
  gravarMarcador(raiz, 'instalado', det);
  return { criados, mantidos, destino, deteccao: det };
}

function gravarMarcador(raiz, modo, det) {
  fs.mkdirSync(dirEscritorio(raiz), { recursive: true });
  fs.writeFileSync(
    path.join(dirEscritorio(raiz), 'agentes.json'),
    JSON.stringify({ configurado: true, modo, em: new Date().toISOString(), stacks: det.stacks.map((s) => s.nome) }, null, 2),
  );
}

function resumo(det) {
  const stacks = det.stacks.length ? det.stacks.map((s) => `${s.nome} [${s.evidencia}]`).join('; ') : 'nenhuma detectada';
  const cmds = [...Object.entries(det.comandos), ...Object.entries(det.convencao).map(([k, v]) => [`${k}(convenção)`, v])];
  return `stack: ${stacks}\ncomandos: ${cmds.length ? cmds.map(([k, v]) => `${k}=${v}`).join('; ') : 'nenhum detectado'}`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const [cmd] = args._;
  const raiz = raizRepo();
  if (cmd === 'verificar') {
    const e = estado(raiz);
    if (e.configurado) { console.log(`AGENTES: CONFIGURADO (${e.marcador?.modo ?? 'agentes do projeto'})`); return; }
    console.log('AGENTES: PENDENTE (primeira execução neste projeto)');
    console.log(`no projeto (.claude/agents): ${e.noProjeto.join(', ') || 'nenhum'}; faltam: ${e.faltam.join(', ')}`);
    console.log(`no usuário (~/.claude/agents), genéricos: ${e.noUsuario.join(', ') || 'nenhum'}`);
    console.log(resumo(detectar(raiz)));
  } else if (cmd === 'detectar') {
    console.log(JSON.stringify(detectar(raiz), null, 2));
  } else if (cmd === 'instalar') {
    const r = instalar(raiz, { sobrescrever: args.sobrescrever === true });
    console.log(`criados: ${r.criados.join(', ') || 'nenhum'}\nmantidos (já existiam): ${r.mantidos.join(', ') || 'nenhum'}\ndestino: ${r.destino}\n${resumo(r.deteccao)}`);
  } else if (cmd === 'dispensar') {
    gravarMarcador(raiz, 'genericos', detectar(raiz));
    console.log('registrado: este projeto usa os agentes genéricos');
  } else {
    console.error('uso: agentes.mjs verificar | detectar | instalar [--sobrescrever] | dispensar');
    process.exit(2);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
